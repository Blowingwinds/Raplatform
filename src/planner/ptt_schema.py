"""PTT (Goal → Tactic → Technique → Action) tree schema.

The PTT tree is the hive's living plan:
- **Static part** (PTTPlan): generated by the Planner Provider, immutable contract
- **Runtime part** (PTTNodeStatus / ActionNode): evolved by the hive during execution

Design principle: Actions are structured task contracts, not platform-maintained operator libraries.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator

from src.domain.models import RiskLevel


class PTTNodeStatus(StrEnum):
    """Runtime status of a PTT tree node during hive execution."""
    PLANNED = "planned"           # generated but not yet dispatched
    READY = "ready"               # dependencies satisfied, can be dispatched
    RUNNING = "running"           # currently being executed by a worker bee
    SUCCEEDED = "succeeded"       # completed successfully
    FAILED = "failed"             # execution failed
    BLOCKED = "blocked"           # cannot proceed (scope/risk/lease/approval)
    SKIPPED = "skipped"           # pruned — made irrelevant by new findings


# ── action contract (static) ─────────────────────────────────────────────

class ActionContract(BaseModel):
    """Structured task contract for a single Action.

    This is the *immutable* part of the plan — what must be done, with what
    constraints, and what outputs are expected. The hive wraps this in an
    ActionNode to track runtime state.
    """

    model_config = ConfigDict(extra="forbid")

    action_id: str = Field(min_length=1, description="Unique action identifier")
    name: str = Field(min_length=1, description="Human-readable action name")
    description: str = Field(min_length=1, description="What this action does")
    technique_id: str = Field(min_length=1, description="ATT&CK technique ID, e.g. T1046")
    target_refs: list[str] = Field(
        min_length=1,
        description="Target asset references this action applies to. '*' means all in-scope.",
    )
    expected_outputs: list[str] = Field(
        min_length=1,
        description="Fact types this action must produce, e.g. ['service.exposed', 'fingerprint.detected']",
    )
    risk_level: RiskLevel = Field(description="Risk level of this action")
    side_effects: list[str] = Field(
        default_factory=list,
        description="Known side effects, e.g. 'may trigger WAF alerts'",
    )
    stop_conditions: list[str] = Field(
        default_factory=list,
        description="Conditions under which the action must stop",
    )

    @field_validator("expected_outputs")
    @classmethod
    def must_have_outputs(cls, v: list[str]) -> list[str]:
        if not v:
            raise ValueError("action requires at least one expected_output")
        return v


# ── technique node ───────────────────────────────────────────────────────

class TechniqueNode(BaseModel):
    """A technique in the PTT tree, containing one or more actions."""

    model_config = ConfigDict(extra="forbid")

    technique_id: str = Field(min_length=1, description="ATT&CK technique ID")
    name: str = Field(min_length=1, description="Human-readable technique name")
    actions: list[ActionContract] = Field(
        min_length=1, description="Actions under this technique"
    )


# ── tactic node ──────────────────────────────────────────────────────────

class TacticNode(BaseModel):
    """A tactic in the PTT tree, containing one or more techniques."""

    model_config = ConfigDict(extra="forbid")

    tactic_id: str = Field(min_length=1, description="ATT&CK tactic ID, e.g. 'reconnaissance'")
    name: str = Field(min_length=1, description="Human-readable tactic name")
    techniques: list[TechniqueNode] = Field(
        min_length=1, description="Techniques under this tactic"
    )


# ── static plan (generated by provider, immutable) ───────────────────────

class PTTPlan(BaseModel):
    """Static PTT plan generated by a Planner Provider.

    This is the output of the planning phase. It is *immutable* once validated.
    The hive wraps this in a PTTTree to add runtime state.
    """

    model_config = ConfigDict(extra="forbid")

    plan_id: str = Field(min_length=1, description="Unique plan identifier")
    goal: str = Field(min_length=1, description="Original user goal (natural language)")
    normalized_goal: str = Field(min_length=1, description="Normalized / canonical goal text")
    project_id: str = Field(min_length=1)
    scope_id: str = Field(min_length=1)
    tactics: list[TacticNode] = Field(min_length=1, description="Tactics in execution order")
    generated_by: str = Field(default="mock", description="Provider identifier")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # ── convenience accessors ──────────────────────────────────────────

    def all_actions(self) -> list[ActionContract]:
        """Flatten all actions in the plan."""
        actions: list[ActionContract] = []
        for tactic in self.tactics:
            for technique in tactic.techniques:
                actions.extend(technique.actions)
        return actions

    def all_techniques(self) -> list[TechniqueNode]:
        """Flatten all technique nodes."""
        techs: list[TechniqueNode] = []
        for tactic in self.tactics:
            techs.extend(tactic.techniques)
        return techs

    def technique_ids(self) -> set[str]:
        """All unique ATT&CK technique IDs in the plan."""
        return {t.technique_id for t in self.all_techniques()}

    def tactic_ids(self) -> set[str]:
        """All unique tactic IDs in the plan."""
        return {t.tactic_id for t in self.tactics}


# ── runtime node wrapper (hive evolves this) ─────────────────────────────

class ActionNode(BaseModel):
    """Runtime wrapper around an ActionContract — the hive tracks state here.

    The static ActionContract is immutable. This node adds:
    - Execution status (PLANNED → RUNNING → SUCCEEDED/FAILED)
    - Evidence references from completed executions
    - Dynamically appended child actions (e.g. discovered service → new scan)
    """

    model_config = ConfigDict(extra="forbid")

    action: ActionContract
    status: PTTNodeStatus = PTTNodeStatus.PLANNED
    evidence_refs: list[str] = Field(default_factory=list)
    child_actions: list[str] = Field(
        default_factory=list,
        description="Action IDs of dynamically appended child actions",
    )
    result_summary: str = ""

    def mark_ready(self) -> None:
        if self.status != PTTNodeStatus.PLANNED:
            raise ValueError(f"Cannot mark {self.action.action_id} as READY (currently {self.status})")
        self.status = PTTNodeStatus.READY

    def mark_running(self) -> None:
        if self.status not in (PTTNodeStatus.READY, PTTNodeStatus.PLANNED):
            raise ValueError(f"Cannot mark {self.action.action_id} as RUNNING (currently {self.status})")
        self.status = PTTNodeStatus.RUNNING

    def mark_succeeded(self, evidence_refs: list[str] | None = None, summary: str = "") -> None:
        self.status = PTTNodeStatus.SUCCEEDED
        if evidence_refs:
            self.evidence_refs.extend(evidence_refs)
        if summary:
            self.result_summary = summary

    def mark_failed(self, reason: str = "") -> None:
        self.status = PTTNodeStatus.FAILED
        if reason:
            self.result_summary = reason

    def mark_blocked(self, reason: str = "") -> None:
        self.status = PTTNodeStatus.BLOCKED
        if reason:
            self.result_summary = reason

    def mark_skipped(self, reason: str = "") -> None:
        self.status = PTTNodeStatus.SKIPPED
        if reason:
            self.result_summary = reason


# ── live PTT tree (hive's operational plan) ──────────────────────────────

class PTTTree(BaseModel):
    """The hive's living PTT tree — created by Planner, evolved by HiveOrchestrator.

    Contains both the static plan and the runtime state map. The hive:
    1. Reads the tree to find READY actions
    2. Dispatches worker bees to execute them
    3. Updates node states and appends new child actions based on blackboard deltas
    4. Re-evaluates readiness after each round
    """

    model_config = ConfigDict(extra="forbid")

    plan: PTTPlan
    node_states: dict[str, PTTNodeStatus] = Field(
        default_factory=dict,
        description="action_id → current runtime status",
    )
    dynamic_nodes: dict[str, ActionNode] = Field(
        default_factory=dict,
        description="Dynamically appended action nodes (not in the original plan)",
    )

    # ── factory ────────────────────────────────────────────────────────

    @classmethod
    def from_plan(cls, plan: PTTPlan) -> PTTTree:
        """Create a live tree from a static plan — all actions start PLANNED."""
        states: dict[str, PTTNodeStatus] = {}
        for action in plan.all_actions():
            states[action.action_id] = PTTNodeStatus.PLANNED
        return cls(plan=plan, node_states=states)

    # ── query ──────────────────────────────────────────────────────────

    def ready_actions(self) -> list[ActionContract]:
        """Return all actions currently in READY state."""
        ready_ids = {
            aid for aid, status in self.node_states.items()
            if status == PTTNodeStatus.READY
        }
        return [a for a in self.plan.all_actions() if a.action_id in ready_ids]

    def planned_actions(self) -> list[ActionContract]:
        """Return all actions still in PLANNED state."""
        planned_ids = {
            aid for aid, status in self.node_states.items()
            if status == PTTNodeStatus.PLANNED
        }
        return [a for a in self.plan.all_actions() if a.action_id in planned_ids]

    def succeeded_actions(self) -> list[ActionContract]:
        """Return all successfully completed actions."""
        ok_ids = {
            aid for aid, status in self.node_states.items()
            if status == PTTNodeStatus.SUCCEEDED
        }
        return [a for a in self.plan.all_actions() if a.action_id in ok_ids]

    def blocked_actions(self) -> list[ActionContract]:
        """Return all blocked actions."""
        blocked_ids = {
            aid for aid, status in self.node_states.items()
            if status == PTTNodeStatus.BLOCKED
        }
        return [a for a in self.plan.all_actions() if a.action_id in blocked_ids]

    def is_complete(self) -> bool:
        """True when all actions have reached a terminal state."""
        terminal = {PTTNodeStatus.SUCCEEDED, PTTNodeStatus.FAILED,
                     PTTNodeStatus.BLOCKED, PTTNodeStatus.SKIPPED}
        return all(s in terminal for s in self.node_states.values())

    def progress(self) -> dict[str, int]:
        """Return progress stats {total, planned, ready, running, succeeded, failed, blocked, skipped}."""
        stats: dict[str, int] = {
            "total": len(self.node_states),
            "planned": 0, "ready": 0, "running": 0,
            "succeeded": 0, "failed": 0, "blocked": 0, "skipped": 0,
        }
        for status in self.node_states.values():
            key = status.value
            if key in stats:
                stats[key] += 1
        return stats

    # ── mutation (hive calls these) ────────────────────────────────────

    def set_status(self, action_id: str, status: PTTNodeStatus) -> None:
        """Update the runtime status of an action node."""
        if action_id not in self.node_states:
            raise ValueError(f"Unknown action_id: {action_id}")
        self.node_states[action_id] = status

    def add_dynamic_node(self, node: ActionNode) -> None:
        """Append a dynamically discovered action to the tree."""
        if node.action.action_id in self.node_states:
            raise ValueError(f"Action {node.action.action_id} already exists")
        self.dynamic_nodes[node.action.action_id] = node
        self.node_states[node.action.action_id] = node.status

    # ── serialization ──────────────────────────────────────────────────

    def summary(self) -> dict[str, Any]:
        """Human-readable summary for CLI / report output."""
        return {
            "plan_id": self.plan.plan_id,
            "goal": self.plan.goal,
            "generated_by": self.plan.generated_by,
            "tactics": len(self.plan.tactics),
            "techniques": len(self.plan.all_techniques()),
            "actions": len(self.plan.all_actions()),
            "progress": self.progress(),
        }